def _ver(fname):
    """?v=<md5[:8]> по содержимому файла — кэш-бастинг: браузер тянет свежий ассет только при изменении."""
    try:
        h = hashlib.md5(open(os.path.join(ROOT, fname), "rb").read()).hexdigest()[:8]
        return "?v=" + h
    except OSError:
        return ""

